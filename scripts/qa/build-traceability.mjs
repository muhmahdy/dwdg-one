// Builds docs/audit/traceability-matrix.md: every PRD node id cited by the prototype (where the requirement trail started), where the
// React app implements it, and which test names it. Ids are found the same way in all three places: as words in source comments,
// strings or test titles. A prototype file that cites an id also tells which React modules inherited that behaviour (PORTED), so the
// matrix points at the React code even when the React source does not repeat the id.
// Usage: node scripts/qa/build-traceability.mjs
import {readFileSync, readdirSync, statSync, existsSync, writeFileSync} from 'node:fs';
import {join, relative} from 'node:path';

const ws = JSON.parse(readFileSync('.planning/dwdg-one-prd/state/planning-workspace.json', 'utf8'));
const byId = Object.fromEntries(ws.prd.nodes.map(n => [n.id, n]));

function cite(dir, {tests = false} = {}) {
  const hits = {};
  if (!existsSync(dir)) return hits;
  const files = [];
  (function walk(d) {
    for (const f of readdirSync(d)) {
      if (f === 'node_modules' || f === 'dist') continue;
      const p = join(d, f);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.(js|mjs|ts|tsx)$/.test(f) && !/(^|[\\/])(qa|assets|i18n)\.js$/.test(p) && (tests ? /\.(test|spec)\./.test(f) : !/\.(test|spec)\./.test(f))) files.push(p);
    }
  })(dir);
  for (const f of files) readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
    for (const m of line.matchAll(/[a-z][a-z0-9]*(?:[-_][a-z0-9]+)+/g)) if (byId[m[0]]) (hits[m[0]] ||= new Set()).add(`${relative('.', f).split('\\').join('/')}:${i + 1}`);
  });
  return hits;
}

// Prototype source file -> the React code that replaced it (docs/audit/feature-matrix.md has the page-by-page view).
const PORTED = {
  'core/app.js': ['src/app/', 'src/layouts/', 'src/lib/workspace/', 'src/components/shared/'],
  'core/data.js': ['database/seeds/demo-workspace.json', 'src/lib/workspace/'],
  'core/persistence.js': ['src/lib/workspace/', 'src/lib/supabase/'],
  'core/i18n.js': ['src/lib/i18n/'],
  'core/icons.js': ['src/components/ui/Icon.tsx'],
  'core/ui-polish.js': ['src/components/ui/', 'src/lib/placement.ts'],
  'screens/calm-shell.js': ['src/layouts/ComfortableShell.tsx'],
  'screens/friendly.js': ['src/layouts/', 'src/features/looks/', 'src/components/shared/shell-menus.tsx'],
  'screens/simple.js': ['src/layouts/SimpleShell.tsx', 'src/features/simple/'],
  'screens/pins.js': ['src/features/pins/'],
  'screens/work.js': ['src/features/work/', 'src/features/operations/'],
  'screens/handin.js': ['src/features/work/'],
  'screens/people.js': ['src/features/collaboration/', 'src/features/people/'],
  'screens/plan.js': ['src/features/projects/', 'src/features/programs/', 'src/features/resources/', 'src/features/updates/', 'src/features/settings/', 'src/features/organisation/'],
  'screens/schedule.js': ['src/features/schedule/'],
  'screens/perf.js': ['src/features/performance/'],
  'screens/accounts.js': ['src/features/accounts/', 'src/features/auth/'],
  'divisions/div-hr-sng.js': ['src/features/hr/', 'src/features/strategy/'],
  'divisions/div-ee-cons.js': ['src/features/external/', 'src/features/consulting/'],
  'divisions/div-fnl-mcit.js': ['src/features/fnl/', 'src/features/mcit/'],
};
const ported = set => { const out = new Set(); for (const ref of set || []) { const file = ref.replace(/^frontend\/prototype\//, '').replace(/:\d+$/, ''); for (const m of PORTED[file] || []) out.add(m); } return [...out]; };

const proto = cite('frontend/prototype');
const react = cite('frontend/src');
const tests = {...cite('frontend/src', {tests: true}), ...cite('frontend/tests', {tests: true})};
const ids = Object.keys(proto).sort();
const branch = id => { let n = byId[id]; const path = []; while (n && n.parent && n.parent !== 'root') { path.unshift(n.parent); n = byId[n.parent]; } return path[1] || path[0] || ''; };
const short = set => !set ? '' : [...set].slice(0, 3).join('<br>') + (set.size > 3 ? `<br>+${set.size - 3} more` : '');
const groups = {};
for (const id of ids) (groups[branch(id)] ||= []).push(id);

let md = `# Traceability matrix\n\nGenerated by \`node scripts/qa/build-traceability.mjs\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n\n`;
md += `Each row is a PRD requirement (planning workspace revision ${ws.revision}) that the prototype source cites by id. The prototype column is where the requirement trail started and is kept as history. The **React implementation** column is the source going forward: it lists \`frontend/src\` files that cite the id, then (as "Ported to") the React modules that replaced the prototype file that cites it, so every row points at React code. A requirement is **verified** only when a test cites it and passes.\n\n`;
const done = ids.filter(id => react[id]).length, mapped = ids.filter(id => react[id] || ported(proto[id]).length).length, tested = ids.filter(id => tests[id]).length;
md += `Summary: ${ids.length} requirements cited by the prototype · ${mapped} point at React code (${done} cited by id in the React source, the rest through the module that replaced the citing prototype file) · ${tested} cited by a test.\n\n`;
const reactCell = id => [short(react[id]), ported(proto[id]).length ? `Ported to: ${ported(proto[id]).map(m => `\`${m}\``).join(', ')}` : ''].filter(Boolean).join('<br>') || 'Not mapped';
for (const [g, list] of Object.entries(groups).sort()) {
  md += `## ${g || 'other'} (${list.length})\n\n| PRD id | Requirement | PRD status | Prototype origin (history) | React implementation | Verification |\n|---|---|---|---|---|---|\n`;
  for (const id of list) md += `| \`${id}\` | ${byId[id].title.replace(/\|/g, '/')} | ${byId[id].status} | ${short(proto[id])} | ${reactCell(id)} | ${short(tests[id]) || 'Not verified'} |\n`;
  md += '\n';
}
writeFileSync('docs/audit/traceability-matrix.md', md);
console.log(`traceability: ${ids.length} ids, ${mapped} point at React code (${done} cited by id), ${tested} tested`);
