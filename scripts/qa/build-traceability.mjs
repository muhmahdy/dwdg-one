// Builds docs/audit/traceability-matrix.md: every PRD node id cited by the prototype, where the React app implements it,
// and which test names it. Ids are found the same way in all three places: as words in source comments, strings or test titles.
// Usage: node scripts/qa/build-traceability.mjs
import {readFileSync, readdirSync, statSync, existsSync, writeFileSync} from 'node:fs';
import {join, relative} from 'node:path';

const ws = JSON.parse(readFileSync('.planning/dwdg-one-prd/state/planning-workspace.json', 'utf8'));
const byId = Object.fromEntries(ws.prd.nodes.map(n => [n.id, n]));

function cite(dir, {tests = false} = {}) {
  const hits = {};
  if (!existsSync(dir)) return hits;
  const files = [];
  (function walk(d) {
    for (const f of readdirSync(d)) {
      if (f === 'node_modules' || f === 'dist') continue;
      const p = join(d, f);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.(js|mjs|ts|tsx)$/.test(f) && !/(^|[\\/])(qa|assets|i18n)\.js$/.test(p) && (tests ? /\.(test|spec)\./.test(f) : !/\.(test|spec)\./.test(f))) files.push(p);
    }
  })(dir);
  for (const f of files) readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
    for (const m of line.matchAll(/[a-z][a-z0-9]*(?:[-_][a-z0-9]+)+/g)) if (byId[m[0]]) (hits[m[0]] ||= new Set()).add(`${relative('.', f).split('\\').join('/')}:${i + 1}`);
  });
  return hits;
}

const proto = cite('frontend/prototype');
const react = cite('frontend/src');
const tests = {...cite('frontend/src', {tests: true}), ...cite('frontend/tests', {tests: true})};
const ids = Object.keys(proto).sort();
const branch = id => { let n = byId[id]; const path = []; while (n && n.parent && n.parent !== 'root') { path.unshift(n.parent); n = byId[n.parent]; } return path[1] || path[0] || ''; };
const short = set => !set ? '' : [...set].slice(0, 3).join('<br>') + (set.size > 3 ? `<br>+${set.size - 3} more` : '');
const groups = {};
for (const id of ids) (groups[branch(id)] ||= []).push(id);

let md = `# Traceability matrix\n\nGenerated by \`node scripts/qa/build-traceability.mjs\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n\n`;
md += `Each row is a PRD requirement (planning workspace revision ${ws.revision}) that the prototype source cites by id. "React implementation" and "Verification" list the files in \`frontend/src\` and the tests that cite the same id, so the matrix fills in as features are migrated. A requirement is **verified** only when a test cites it and passes.\n\n`;
const done = ids.filter(id => react[id]).length, tested = ids.filter(id => tests[id]).length;
md += `Summary: ${ids.length} requirements cited by the prototype · ${done} cited by the React app · ${tested} cited by a test.\n\n`;
for (const [g, list] of Object.entries(groups).sort()) {
  md += `## ${g || 'other'} (${list.length})\n\n| PRD id | Requirement | PRD status | Prototype | React implementation | Verification |\n|---|---|---|---|---|---|\n`;
  for (const id of list) md += `| \`${id}\` | ${byId[id].title.replace(/\|/g, '/')} | ${byId[id].status} | ${short(proto[id])} | ${short(react[id]) || 'Not migrated'} | ${short(tests[id]) || 'Not verified'} |\n`;
  md += '\n';
}
writeFileSync('docs/audit/traceability-matrix.md', md);
console.log(`traceability: ${ids.length} ids, ${done} implemented, ${tested} tested`);
