// Writes one SQL file per project (database/bundles/hub.sql, ee.sql, mcit.sql, hr.sql, fnl.sql, sng.sql, cons.sql) that holds
// all the migrations of that project in the right order, so a whole project can be set up by pasting ONE file into the
// Supabase SQL editor (or running it with psql). Run it again after the schema changes; the bundles are not committed.
//   node scripts/database/bundle-migrations.mjs [--out database/bundles]
// A bundle is for a NEW, EMPTY project. The migrations create tables and functions; they do not check whether they exist.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '../../database');
const arg = name => { const i = process.argv.indexOf(name); return i > -1 ? process.argv[i + 1] : undefined; };
const out = path.resolve(arg('--out') ?? path.join(root, 'bundles'));
const SPOKES = ['ee', 'mcit', 'hr', 'fnl', 'sng', 'cons'];

const filesIn = dir => fs.readdirSync(path.join(root, dir)).filter(f => f.endsWith('.sql')).sort().map(f => `${dir}/${f}`);
const read = f => fs.readFileSync(path.join(root, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();

/** The files of each project, in the order they must run. */
export const BUNDLES = {
  hub: filesIn('hub/migrations'),
  ...Object.fromEntries(SPOKES.map(s => [s, [...filesIn('spoke/base/migrations'), ...filesIn(`spoke/${s}/migrations`)]])),
};

export function bundleText(project) {
  const files = BUNDLES[project];
  return `-- DWDG'ONE ${project === 'hub' ? 'hub' : `division project "${project}"`}: every migration, in order, in one file.
-- GENERATED by scripts/database/bundle-migrations.mjs. For a NEW, EMPTY project only. Do not edit; do not run twice.
-- Files: ${files.join(', ')}

${files.map(f => `-- ======================================================================================================
-- ${f}
-- ======================================================================================================
${read(f)}
`).join('\n')}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(out, {recursive: true});
  for (const project of Object.keys(BUNDLES)) {
    const file = path.join(out, `${project}.sql`);
    fs.writeFileSync(file, bundleText(project));
    console.log(`${path.relative(process.cwd(), file)}: ${BUNDLES[project].length} migrations, ${(fs.statSync(file).size / 1024).toFixed(0)} KiB`);
  }
}
