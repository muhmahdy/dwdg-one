// Reads database/migrations/*.sql and writes database/relations/ERD.md:
// a Mermaid entity-relationship diagram plus a foreign-key table, derived from the `references` clauses.
// Run: node bin/generate-db-relations.mjs   (re-run after adding a migration)
import {readFileSync, readdirSync, writeFileSync, mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root = new URL('../', import.meta.url);
const dir = fileURLToPath(new URL('database/migrations/', root));
const files = readdirSync(dir).filter(f => f.endsWith('.sql')).sort();

// How the tables read in the product (naming-based grouping, not stored in the SQL).
const GROUPS = [
  ['Identity and access', ['divisions', 'invitations', 'profiles', 'memberships']],
  ['Projects and work', ['projects', 'project_catalog', 'project_divisions', 'project_access', 'tasks', 'task_dependencies', 'project_dependencies', 'milestones', 'blockers']],
  ['Meetings, decisions, documents', ['meetings', 'meeting_attendees', 'decisions', 'documents']],
  ['Activity and notifications', ['activity_events', 'notifications']],
  ['Division workflows', ['workflow_stages', 'initiatives', 'finance_budgets', 'finance_approvers', 'finance_requests', 'finance_request_history', 'hr_journeys', 'hr_checklist_items', 'marketing_deliverables', 'division_records']],
  ['Admin, import and catalog', ['legacy_imports', 'finance_budget_catalog']]
];

const tables = new Map(); // name -> {file}
const links = [];         // {table, column, target, required, onDelete}
let current = null;
for (const file of files) {
  for (const line of readFileSync(dir + file, 'utf8').split('\n')) {
    const create = line.match(/^create table (?:if not exists )?((?:public|private)\.\w+)/i);
    if (create) { current = create[1]; tables.set(current, {file}); continue; }
    if (/^\);/.test(line)) { current = null; continue; }
    if (!current) continue;
    const ref = line.match(/references\s+((?:public|private|auth)\.\w+)\((\w+)\)(.*)$/i);
    const column = line.trim().match(/^(\w+)\s/);
    if (!ref || !column || /^(constraint|foreign|primary|unique|check)$/i.test(column[1])) continue;
    const onDelete = (ref[3].match(/on delete (cascade|set null|restrict|no action)/i) || [])[1] || 'no action';
    links.push({table: current, column: column[1], target: ref[1], targetColumn: ref[2], required: /\bnot null\b|primary key/i.test(line), onDelete});
  }
}

const short = name => name.replace(/^public\./, '').replace(/^auth\./, 'auth_').replace(/^private\./, 'private_');
const out = [];
out.push('# Database relations', '');
out.push('Generated by `bin/generate-db-relations.mjs` from the `references` clauses in `database/migrations/*.sql`. Do not edit by hand; re-run the script after adding a migration. The SQL files remain the source of truth.', '');
out.push(`${tables.size} tables, ${links.length} foreign keys, ${files.length} migrations.`, '');
out.push('## Table groups', '');
for (const [title, names] of GROUPS) out.push(`- **${title}:** ${names.map(n => `\`${n}\``).join(', ')}`);
const grouped = new Set(GROUPS.flatMap(([, n]) => n));
const other = [...tables.keys()].map(short).filter(n => !grouped.has(n) && !n.startsWith('private_'));
if (other.length) out.push(`- **Other:** ${other.map(n => `\`${n}\``).join(', ')}`);
out.push('', 'Also present: the `public.finance_budget_summary` view (migration 202609230003) and `private.bootstrap_settings`, which holds the first-administrator setting described in `database/README.md`.', '');
out.push('## Diagram', '', 'A solid line marks a required reference (`not null`); a line with a circle marks an optional one. Read each line as parent → child.', '');
out.push('```mermaid', 'erDiagram');
for (const l of links) {
  const parent = short(l.target), child = short(l.table);
  out.push(`  ${parent} ${l.required ? '||' : '|o'}--o{ ${child} : "${l.column}"`);
}
out.push('```', '');
out.push('## By feature', '', "One diagram per table group: the group's own tables plus the outside tables they point to.", '');
for (const [title, names] of GROUPS) {
  const own = links.filter(l => names.includes(short(l.table)));
  if (!own.length) continue;
  out.push(`### ${title}`, '', 'Tables: ' + names.map(n => '`' + n + '`').join(', '), '', '```mermaid', 'erDiagram');
  for (const l of own) out.push(`  ${short(l.target)} ${l.required ? '||' : '|o'}--o{ ${short(l.table)} : "${l.column}"`);
  out.push('```', '');
}
out.push('## Foreign keys', '', '| Table | Column | References | Required | On delete |', '|---|---|---|---|---|');
for (const l of links) out.push(`| ${short(l.table)} | ${l.column} | ${short(l.target)}.${l.targetColumn} | ${l.required ? 'yes' : 'no'} | ${l.onDelete} |`);
out.push('');

mkdirSync(new URL('database/relations/', root), {recursive: true});
writeFileSync(new URL('database/relations/ERD.md', root), out.join('\n'));
console.log(`database/relations/ERD.md: ${tables.size} tables, ${links.length} foreign keys`);
