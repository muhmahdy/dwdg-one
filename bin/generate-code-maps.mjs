// Writes two maps from the source, so they cannot drift from the code:
//   docs/PAGE_MAP.md              every page of the three frontends, and the file that renders it
//   backend/client/API_MAP.md     every backend operation, grouped by feature, with the tables it touches
// Run: node bin/generate-code-maps.mjs   (re-run after adding a page or a backend operation)
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';

const read = p => readFileSync(p, 'utf8');
const walk = d => readdirSync(d, {withFileTypes: true}).flatMap(e => e.isDirectory() ? walk(`${d}/${e.name}`) : [`${d}/${e.name}`]);
const lineOf = (text, index) => text.slice(0, index).split('\n').length;
const cell = v => String(v).replace(/\|/g, '\\|');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(r => `| ${r.map(cell).join(' | ')} |`)];

// ------------------------------------------------------------------ pages
const SRC = 'frontend/app/src';
const out = ['# Page map', ''];
out.push('Generated by `bin/generate-code-maps.mjs` from the source. Do not edit by hand. Line numbers point to the code that renders each page.', '');

// 1. Workspace app (v1.1)
const expFiles = walk(`${SRC}/experience`).filter(f => f.endsWith('.mjs') && !f.endsWith('.test.mjs'));
const defOf = name => {
  for (const f of expFiles) { const t = read(f), m = t.match(new RegExp(`function ${name}\\b`)); if (m) return `${f.slice(SRC.length + 1)}:${lineOf(t, m.index)}`; }
  return '?';
};
const shell = read(`${SRC}/experience/shell/experience.mjs`);
const renderers = Object.fromEntries([...shell.match(/const renderers=\{([^\n]*)\};/)[1].matchAll(/(\w+):(?:\(\)=>)?(render\w+)/g)].map(m => [m[1], m[2]]));
const primary = [...read(`${SRC}/experience/i18n/experience-i18n.mjs`).match(/PRIMARY_PAGES = \[([\s\S]*?)\n\];/)[1].matchAll(/\['(\w+)','([^']+)','([^']+)'/g)];
out.push('## 1. Workspace app (`frontend/app/index.html`, v1.1)', '', 'Hash routes, rendered by `experience/shell/experience.mjs`. English / Indonesian labels come from the shared language system.', '');
out.push(...table(['Route', 'Page (EN / ID)', 'Rendered by'], [
  ...primary.map(m => [`#${m[1]}`, `${m[2]} / ${m[3]}`, defOf(renderers[m[1]] || 'renderHome')]),
  ['#project/<id>', 'Project detail', defOf(renderers.project)],
  ['#division/<slug>', 'Division workspace (six divisions)', defOf(renderers.division)]
]), '');
const divisions = [...read(`${SRC}/experience/data/experience-records.mjs`).matchAll(/\{slug:'([\w-]+)',name:'([^']+)'/g)];
out.push(`Divisions: ${divisions.map(m => `\`${m[1]}\` (${m[2]})`).join(', ')}.`, '');

// 2. dwdg'ONE preview
const preview = read(`${SRC}/dwdg-one/shell/dwdg-one-preview.mjs`);
const nav = [...preview.match(/const NAV = \[([\s\S]*?)\n\];/)[1].matchAll(/\['(\w+)','([^']+)','([^']+)'/g)];
const wired = new Set([...preview.matchAll(/v\.route==='(\w+)'/g)].map(m => m[1]));
const FEATURE = {home: 'features/home', work: 'features/work', projects: 'features/projects (project page, stages) and the project list in shell', resources: 'features/resources', changes: 'features/projects (renderLocalChanges)'};
out.push("## 2. dwdg'ONE preview (`frontend/app/dwdg-one-preview.html`)", '', 'Routes dispatched in `render()` in `dwdg-one/shell/dwdg-one-preview.mjs`. A route without a branch there shows the "Coming" placeholder.', '');
out.push(...table(['Route', 'Page (EN / ID)', 'Status', 'Feature folder (`dwdg-one/`)'], nav.map(m => [
  `#${m[1]}`, `${m[2]} / ${m[3]}`, wired.has(m[1]) ? 'rendered' : 'placeholder ("Coming")', wired.has(m[1]) ? FEATURE[m[1]] || '—' : '—'
])), '');
out.push('Supporting folders: `shell/` (frame, preferences, effects, accessibility), `data/` (the local preview store), `features/daily/` (today and due grouping), `features/notes/` (notes), `features/access/` (roles and workspace access), `features/schedule/` (schedule data helpers; not yet wired to a page).', '');

// 3. Prototype
out.push('## 3. Clickable prototype (`frontend/prototype/index.html`)', '', 'Pages register themselves in one `PAGES` table. Scripts share a global scope and load in the order listed in `index.html`.', '');
const rows = [];
for (const f of walk('frontend/prototype').filter(f => f.endsWith('.js') && !f.endsWith('assets.js'))) {
  const t = read(f);
  for (const m of t.matchAll(/^\s*PAGES(?:\.([A-Za-z]\w*)|\['([\w-]+)'\])\s*=/gm)) rows.push([m[1] || m[2], f.replace('frontend/prototype/', ''), lineOf(t, m.index)]);
}
const seen = new Map();
for (const [key, file, line] of rows) { const k = `${key}`; seen.set(k, [...(seen.get(k) || []), `${file}:${line}`]); }
out.push(...table(['Page key', 'Defined in (file:line)'], [...seen].sort((a, b) => a[0].localeCompare(b[0])).map(([k, v]) => [`\`${k}\``, v.join(', ')])), '');
out.push('A key listed more than once is assigned by several scripts. The last script loaded wins; the `updates` pages in the division scripts call the earlier page (`base(r)`) and add to it.', '');
writeFileSync('docs/PAGE_MAP.md', out.join('\n'));

// ------------------------------------------------------------------ backend
const bsrc = read('backend/client/shared-backend.mjs');
const GROUPS = [
  ['Session and sign-in', ['user', 'getSession', 'signInWithGoogle', 'signOut', 'onAuthStateChange', 'bootstrap']],
  ['Members, invitations and roles', ['listInvitations', 'listMembersWithAccess', 'createInvitation', 'revokeInvitation', 'setMembership', 'removeMembership', 'setGlobalRole', 'setProfileName']],
  ['Core work: projects, tasks, meetings', ['loadCoreState', 'projectRow', 'taskRow', 'meetingRow', 'commitCoreChange', 'listProjectCatalog', 'listProjects', 'upsertProject', 'upsertTask', 'listSchedule', 'upsertEvent']],
  ['Project access', ['listProjectAccess', 'setProjectAccess', 'removeProjectAccess']],
  ['Project extras: milestones, blockers, decisions', ['listProjectExtras', 'upsertProjectExtra', 'deleteProjectExtra']],
  ['Documents and files', ['uploadDocument', 'getDocumentDownloadUrl']],
  ['Division workflows', ['listDivisionRecords', 'upsertDivisionRecord', 'listDivisionWorkspace', 'loadDivisionState', 'divisionRow', 'commitDivisionState']],
  ['Finance', ['listBudgetSummary', 'setFinanceApprover', 'transitionApproval']],
  ['Notifications and search', ['listNotifications', 'markNotificationRead', 'search']],
  ['Legacy import', ['importLegacyBackup']],
  ['Realtime', ['subscribeToChanges']]
];
const start = bsrc.indexOf('export async function createBackend');
const body = bsrc.slice(start);
const fnRe = /^  (?:async )?function (\w+)\(/gm;
const fns = [...body.matchAll(fnRe)].map((m, i, all) => ({name: m[1], line: lineOf(bsrc, start + m.index), text: body.slice(m.index, all[i + 1] ? all[i + 1].index : undefined)}));
const touches = text => {
  const t = new Set();
  for (const m of text.matchAll(/query\('(\w+)'\)|\.from\('([\w-]+)'\)|table:'(\w+)'/g)) t.add(m[1] || m[2] || m[3]);
  for (const m of text.matchAll(/\.rpc\('(\w+)'/g)) t.add(`rpc ${m[1]}`);
  if (/DOMAIN_TABLES/.test(text)) t.add('division tables (finance_*, hr_*, initiatives, marketing_*, workflow_stages)');
  if (/EXTRA_TABLES/.test(text)) ['milestones', 'blockers', 'project_dependencies', 'decisions', 'documents'].forEach(x => t.add(x));
  if (/postgres_changes/.test(text)) t.add('realtime changes');
  return [...t].join(', ') || '—';
};
const byName = new Map(fns.map(f => [f.name, f]));
const grouped = new Set(GROUPS.flatMap(([, n]) => n));
const b = ['# Backend API map', ''];
b.push('Generated by `bin/generate-code-maps.mjs` from `shared-backend.mjs`. Do not edit by hand. It lists the functions defined inside `createBackend()` (row mappers such as `projectRow` are internal helpers), grouped by feature, with the tables and database functions each one touches, so a feature can be traced down to `database/migrations/`.', '');
b.push('Top-level exports: `DIVISION_CODES`, `DIVISION_NAMES`, `getBackendConfig()`, `previewLegacyBackup()` (pure, no network), `createBackend()`.', '');
for (const [title, names] of GROUPS) {
  const rowsB = names.filter(n => byName.has(n)).map(n => [`\`${n}\``, byName.get(n).line, touches(byName.get(n).text)]);
  if (!rowsB.length) continue;
  b.push(`## ${title}`, '', ...table(['Operation', 'Line', 'Tables / database functions'], rowsB), '');
}
const rest = fns.filter(f => !grouped.has(f.name));
if (rest.length) b.push('## Not yet grouped', '', ...table(['Operation', 'Line', 'Tables / database functions'], rest.map(f => [`\`${f.name}\``, f.line, touches(f.text)])), '');
writeFileSync('backend/client/API_MAP.md', b.join('\n'));
console.log(`docs/PAGE_MAP.md and backend/client/API_MAP.md written (${fns.length} backend operations, ${seen.size} prototype pages)`);
