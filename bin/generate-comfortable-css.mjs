// Builds frontend/prototype/core/comfortable.gen.css: the Comfortable text sizes for the prototype (D53).
// Members found the original type dizzying: about ten sizes per screen in half-pixel steps, half of the text under 13px.
// This script reads every stylesheet the prototype loads, finds each rule that sets a pixel font size, and re-emits it under
// body[data-density="comfortable"] with the size snapped to a five-step scale (laptop) and a larger one on phones.
// Compact (the original look) is untouched because every generated rule needs the attribute.
// Run: node bin/generate-comfortable-css.mjs   (re-run after any stylesheet change)
import {readFileSync, writeFileSync} from 'node:fs';
import postcss from 'postcss';

const root = new URL('../', import.meta.url);
const P = 'frontend/prototype/';
// Same order as frontend/prototype/index.html, so later rules still win.
const FILES = ['.planning/design/system/components.css', `${P}core/app.css`, `${P}core/screens.css`, `${P}screens/perf.css`, `${P}screens/accounts.css`, `${P}divisions/div-hr-sng.css`, `${P}divisions/div-ee-cons.css`, `${P}divisions/div-fnl-mcit.css`];
const PREFIX = 'body[data-density="comfortable"]';

// The scale. Sizes above 27px are display numbers and art, kept as they are.
const laptop = s => s <= 11.75 ? 13 : s < 13.75 ? 14 : s < 15.75 ? 15 : s <= 20 ? 18 : s <= 27 ? 26 : s;
const phone = s => s <= 11.75 ? 14 : s < 13.75 ? 15 : s < 15.75 ? 17 : s <= 20 ? 20 : s <= 27 ? 30 : s;
// Avatar initials and similar marks sit inside fixed circles; scaling them would overflow the shape.
const SKIP = /(^|[\s>+~,])\.av\b|\.av-|\.bi\b|\.ic\b|\.kbd\b|svg|\.st-ic|\.n-ic|\.w-grip|\.ptl2-ms|\.g-pin/;

const scopeSelector = sel => {
  sel = sel.trim();
  if (/^(:root|html)\b/.test(sel)) return sel.replace(/^(:root|html)(\S*)/, `$1$2 ${PREFIX}`);
  if (/^\[data-theme/.test(sel)) return sel.replace(/^(\[data-theme[^\]]*\]\S*)/, `$1 ${PREFIX}`);
  if (/^body\b/.test(sel)) return sel.replace(/^body/, PREFIX);
  return `${PREFIX} ${sel}`;
};
const px = v => parseFloat(v);
const lineFor = (size, lh) => Math.max(lh || 0, Math.round(size * 1.4));

function build(map) {
  const out = postcss.root();
  let rules = 0;
  for (const file of FILES) {
    const css = postcss.parse(readFileSync(new URL(file, root), 'utf8'), {from: file});
    css.walkRules(rule => {
      if (rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
      const decls = [];
      let size = null, lhDecl = null;
      rule.walkDecls(d => {
        if (d.prop === 'line-height' && /px$/.test(d.value.trim())) lhDecl = d;
        if (d.prop === 'font-size' && /^[\d.]+px$/.test(d.value.trim())) { size = px(d.value); decls.push({prop: 'font-size', value: `${map(size)}px`}); }
        if (d.prop === 'font' && /[\d.]+px/.test(d.value)) {
          const m = d.value.match(/([\d.]+)px(?:\s*\/\s*([\d.]+)(px)?)?/);
          size = px(m[1]); const to = map(size);
          const lh = m[2] ? (m[3] ? `/${lineFor(to, px(m[2]))}px` : `/${m[2]}`) : '';
          decls.push({prop: 'font', value: d.value.replace(m[0], `${to}px${lh}`)});
        }
      });
      if (size == null || map(size) === size) return;
      const sels = rule.selectors.filter(s => !SKIP.test(s));
      if (!sels.length) return;
      if (lhDecl) decls.push({prop: 'line-height', value: `${lineFor(map(size), px(lhDecl.value))}px`});
      const copy = postcss.rule({selector: sels.map(scopeSelector).join(',\n')});
      decls.forEach(d => copy.append(postcss.decl(d)));
      // Keep the media conditions the original rule lives in.
      let node = copy;
      for (let p = rule.parent; p && p.type === 'atrule'; p = p.parent) { const at = postcss.atRule({name: p.name, params: p.params}); at.append(node); node = at; }
      out.append(node); rules++;
    });
  }
  return {out, rules};
}

const L = build(laptop), M = build(phone);
const phoneBlock = postcss.atRule({name: 'media', params: '(max-width: 599px)'});
M.out.nodes.slice().forEach(n => phoneBlock.append(n));
const header = `/* GENERATED by bin/generate-comfortable-css.mjs. Do not edit; change the source stylesheets and re-run.
   Comfortable density (D53): every pixel font size in the prototype snapped to five steps.
   Laptop: up to 11.5 -> 13, 12 to 13.5 -> 14, 14 to 15.5 -> 15, 16 to 20 -> 18, 22 to 27 -> 26.
   Phone (max-width 599px): 14 / 15 / 17 / 20 / 30. Compact (the original look) is untouched. */\n\n`;
writeFileSync(new URL(`${P}core/comfortable.gen.css`, root), header + L.out.toString() + '\n\n/* phones */\n' + phoneBlock.toString() + '\n');
console.log(`comfortable.gen.css: ${L.rules} laptop rules, ${M.rules} phone rules`);
